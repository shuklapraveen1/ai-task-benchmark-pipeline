from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional, Union
import json
import subprocess


@dataclass
class RepoContext:
    repo_path: Path
    repo_url: Optional[str] = None

    ecosystem: str = "unknown"

    package_files: list = field(default_factory=list)
    dependency_files: list = field(default_factory=list)
    declared_python_versions: list = field(default_factory=list)

    test_frameworks: list = field(default_factory=list)
    test_config_files: list = field(default_factory=list)

    coverage_tools: list = field(default_factory=list)
    coverage_config_files: list = field(default_factory=list)

    linters: list = field(default_factory=list)
    linter_config_files: list = field(default_factory=list)

    formatters: list = field(default_factory=list)
    formatter_config_files: list = field(default_factory=list)

    ci_files: list = field(default_factory=list)
    docker_files: list = field(default_factory=list)

    git_commit: Optional[str] = None
    git_branch: Optional[str] = None

    discovered_files: list = field(default_factory=list)
    warnings: list = field(default_factory=list)


def discover_python_versions(path, discovered_files):
    versions = []

    # tox.ini is often the strongest source for the supported
    # test/runtime matrix.
    if "tox.ini" in discovered_files:
        tox_path = path / "tox.ini"

        try:
            content = tox_path.read_text(encoding="utf-8")

            for token in content.split(","):
                token = token.strip()

                if token.startswith("py") and token[2:].replace(".", "").isdigit():
                    version = token[2:]

                    if len(version) == 2:
                        version = "{}.{}".format(version[0], version[1])

                    elif len(version) == 3:
                        version = "{}.{}".format(version[:1], version[1:])

                    if version not in versions:
                        versions.append(version)

                elif token == "pypy3":
                    if "pypy3" not in versions:
                        versions.append("pypy3")

        except OSError:
            pass

    # setup.py can contain Python version classifiers.
    if "setup.py" in discovered_files:
        setup_path = path / "setup.py"

        try:
            content = setup_path.read_text(encoding="utf-8")

            import re

            matches = re.findall(
                r"Programming Language :: Python :: (\d+\.\d+)",
                content,
            )

            for version in matches:
                if version not in versions:
                    versions.append(version)

            if "Programming Language :: Python :: Implementation :: PyPy" in content:
                if "pypy3" not in versions:
                    versions.append("pypy3")

        except OSError:
            pass

    return versions


def discover_repo(
    repo_path: Union[str, Path],
    repo_url: Optional[str] = None,
) -> RepoContext:
    """
    Inspect a local repository and return static repository facts.

    This function must not modify the repository or install anything.
    """

    path = Path(repo_path).resolve()

    if not path.exists():
        raise FileNotFoundError("Repository path does not exist: {}".format(path))

    if not path.is_dir():
        raise ValueError("Repository path is not a directory: {}".format(path))

    context = RepoContext(
        repo_path=path,
        repo_url=repo_url,
    )

    # Discover repository files while excluding directories and files
    # that are normally generated by local development or execution.
    ignored_directories = {
        ".git",
        ".venv",
        "venv",
        "env",
        ".tox",
        "__pycache__",
        ".pytest_cache",
        "node_modules",
    }

    ignored_file_names = {
        ".coverage",
        "coverage.xml",
    }

    ignored_directory_suffixes = {
        ".egg-info",
    }

    for file_path in path.rglob("*"):
        if not file_path.is_file():
            continue

        relative = file_path.relative_to(path)

        # Ignore generated/runtime directories.
        if any(part in ignored_directories for part in relative.parts):
            continue

        # Ignore known generated files.
        if relative.name in ignored_file_names:
            continue

        # Ignore generated package metadata directories such as
        # glom.egg-info/.
        if any(part.endswith(".egg-info") for part in relative.parts):
            continue

        context.discovered_files.append(relative.as_posix())

    context.discovered_files.sort()

    # Python ecosystem detection.
    python_indicators = {
        "setup.py",
        "pyproject.toml",
        "requirements.txt",
        "requirements.in",
        "tox.ini",
    }

    if any(indicator in context.discovered_files for indicator in python_indicators):
        context.ecosystem = "python"

    # Packaging files.
    for filename in (
        "setup.py",
        "setup.cfg",
        "pyproject.toml",
    ):
        if filename in context.discovered_files:
            context.package_files.append(filename)

    # Dependency files.
    dependency_names = (
        "requirements.txt",
        "requirements.in",
        "requirements-dev.txt",
        "requirements-dev.in",
        "Pipfile",
        "Pipfile.lock",
        "poetry.lock",
        "uv.lock",
    )

    for filename in dependency_names:
        if filename in context.discovered_files:
            context.dependency_files.append(filename)

    context.declared_python_versions = discover_python_versions(
        path,
        context.discovered_files,
    )

    # Test configuration.
    test_config_names = (
        "pytest.ini",
        "tox.ini",
        "setup.cfg",
        "pyproject.toml",
    )

    for filename in test_config_names:
        if filename in context.discovered_files:
            context.test_config_files.append(filename)

        # ---------------------------------------------------------
    # Test framework detection
    # ---------------------------------------------------------

    def add_framework(name):
        if name not in context.test_frameworks:
            context.test_frameworks.append(name)

    # pytest.ini is direct evidence that pytest is configured.
    if "pytest.ini" in context.discovered_files:
        add_framework("pytest")

        pytest_config = path / "pytest.ini"

        try:
            content = pytest_config.read_text(encoding="utf-8")

            if "doctest" in content.lower():
                add_framework("doctest")

        except OSError as exc:
            context.warnings.append("Could not read pytest.ini: {}".format(exc))

    # Inspect tox.ini for test commands and doctest options.
    if "tox.ini" in context.discovered_files:
        tox_path = path / "tox.ini"

        try:
            content = tox_path.read_text(encoding="utf-8")

            if "pytest" in content:
                add_framework("pytest")

            if "doctest" in content:
                add_framework("doctest")

        except OSError as exc:
            context.warnings.append("Could not read tox.ini: {}".format(exc))

    # setup.py dependency declarations can provide additional evidence.
    if "setup.py" in context.discovered_files:
        setup_path = path / "setup.py"

        try:
            content = setup_path.read_text(encoding="utf-8")

            if "pytest" in content:
                add_framework("pytest")

            if "unittest" in content:
                add_framework("unittest")

        except OSError as exc:
            context.warnings.append("Could not read setup.py: {}".format(exc))

    # Coverage detection.
    coverage_files = (
        ".coveragerc",
        ".tox-coveragerc",
        "codecov.yml",
    )

    for filename in coverage_files:
        if filename in context.discovered_files:
            context.coverage_config_files.append(filename)

    if context.coverage_config_files:
        context.coverage_tools.append("coverage.py")

    # Linter detection.
    linter_configs = {
        "ruff.toml": "ruff",
        ".ruff.toml": "ruff",
        ".flake8": "flake8",
        "pylintrc": "pylint",
    }

    for filename, tool in linter_configs.items():
        if filename in context.discovered_files:
            context.linters.append(tool)
            context.linter_config_files.append(filename)

    # Formatter detection.
    formatter_configs = {
        ".black": "black",
        "pyproject.toml": None,
    }

    if "pyproject.toml" in context.discovered_files:
        pyproject = path / "pyproject.toml"

        try:
            content = pyproject.read_text(encoding="utf-8")

            if "[tool.black]" in content:
                context.formatters.append("black")
                context.formatter_config_files.append("pyproject.toml")

            if "[tool.ruff.format]" in content:
                if "ruff" not in context.formatters:
                    context.formatters.append("ruff")
                context.formatter_config_files.append("pyproject.toml")

        except OSError as exc:
            context.warnings.append("Could not read pyproject.toml: {}".format(exc))

    # CI detection.
    for file_path in context.discovered_files:
        if file_path.startswith(".github/workflows/"):
            context.ci_files.append(file_path)

    # Docker detection.
    for filename in (
        "Dockerfile",
        "docker-compose.yml",
        "docker-compose.yaml",
        "compose.yml",
        "compose.yaml",
    ):
        if filename in context.discovered_files:
            context.docker_files.append(filename)

    # Git information.
    try:
        context.git_commit = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=str(path),
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()

        context.git_branch = (
            subprocess.check_output(
                ["git", "branch", "--show-current"],
                cwd=str(path),
                stderr=subprocess.DEVNULL,
                text=True,
            ).strip()
            or None
        )

    except (subprocess.CalledProcessError, OSError):
        context.warnings.append("Could not determine Git commit or branch.")

    return context


def context_to_dict(context: RepoContext) -> dict:
    data = asdict(context)
    data["repo_path"] = str(context.repo_path)
    return data


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(
        description="Discover repository structure and tooling."
    )

    parser.add_argument("repo_path")
    parser.add_argument("--repo-url", default=None)

    args = parser.parse_args()

    context = discover_repo(
        args.repo_path,
        repo_url=args.repo_url,
    )

    print(
        json.dumps(
            context_to_dict(context),
            indent=2,
            sort_keys=True,
        )
    )
